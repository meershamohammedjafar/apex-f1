import { chromium } from 'playwright';
const b = await chromium.launch({ args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox','--disable-dev-shm-usage'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
p.setDefaultTimeout(60000);
p.on('pageerror', e => console.log('PAGEERROR', e.message));
await p.goto('http://127.0.0.1:4173/?quality=low', { waitUntil: 'domcontentloaded' });
await p.waitForFunction(() => globalThis.__APEX_READY__ === true || globalThis.__APEX_ERROR__, null, { timeout: 240000 });
await p.waitForTimeout(800);
const row = p.locator('.mm-row', { hasText: 'Difficulty' }).first();
const value = row.locator('.mm-row-text');
const down = row.locator('.mm-arrow').nth(0);
const up = row.locator('.mm-arrow').nth(1);
const seq = { start: await value.textContent() };
await up.click(); seq.up1 = await value.textContent();
await up.click(); seq.up2 = await value.textContent();
await down.click(); seq.down1 = await value.textContent();
await down.click(); seq.down2 = await value.textContent();
console.log('DIFFICULTY', JSON.stringify(seq));
await b.close();
